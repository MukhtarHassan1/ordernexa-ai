"""Per-action progressive autonomy controls.

This module deliberately does not grant authority to an AI agent. It stores and
checks server-side policy for named actions. Consequential write paths remain
separately protected by RBAC, deterministic business rules and the global
external-write switch.
"""
from __future__ import annotations

from decimal import Decimal
from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from app.models.digital_twin import AutonomyPolicy

DEFAULT_POLICIES = {
    "ARCHIVE_VERIFIED_DOCUMENT": {"level": 2, "enabled": False, "allowed_risks": ["LOW", "MEDIUM"]},
    "SYNC_CRM_ACTIVITY": {"level": 2, "enabled": False, "allowed_risks": ["LOW", "MEDIUM"]},
    "CREATE_OUTLOOK_DRAFT": {"level": 2, "enabled": False, "allowed_risks": ["LOW", "MEDIUM", "HIGH"]},
    "SEND_CUSTOMER_EMAIL": {"level": 1, "enabled": False, "allowed_risks": ["LOW"]},
    "CREATE_ERP_ORDER": {"level": 1, "enabled": False, "allowed_risks": ["LOW"]},
    "BYPASS_CREDIT_BLOCK": {"level": 0, "enabled": False, "allowed_risks": []},
    "CHANGE_PAYMENT_DESTINATION": {"level": 0, "enabled": False, "allowed_risks": []},
    "REFUND_PAYMENT": {"level": 0, "enabled": False, "allowed_risks": []},
}


async def seed_default_autonomy_policies(session: AsyncSession, *, actor_id: str) -> list[AutonomyPolicy]:
    created: list[AutonomyPolicy] = []
    for action, cfg in DEFAULT_POLICIES.items():
        row = await session.get(AutonomyPolicy, action)
        if row is None:
            row = AutonomyPolicy(
                action=action,
                level=cfg["level"],
                enabled=cfg["enabled"],
                allowed_risks=cfg["allowed_risks"],
                require_verified_evidence=True,
                notes="Safe default generated by OrderNexa. Enable only after evaluation and live-integration verification.",
                updated_by=actor_id,
            )
            session.add(row)
            created.append(row)
    await session.commit()
    return created


async def list_autonomy_policies(session: AsyncSession) -> list[dict]:
    rows = (await session.execute(select(AutonomyPolicy).order_by(AutonomyPolicy.action))).scalars().all()
    return [
        {
            "action": row.action,
            "level": row.level,
            "enabled": row.enabled,
            "policy_version": row.policy_version,
            "max_value": str(row.max_value) if row.max_value is not None else None,
            "allowed_risks": row.allowed_risks,
            "require_verified_evidence": row.require_verified_evidence,
            "notes": row.notes,
            "updated_by": row.updated_by,
            "updated_at": row.updated_at.isoformat() if row.updated_at else None,
        }
        for row in rows
    ]


async def update_autonomy_policy(
    session: AsyncSession,
    *,
    action: str,
    level: int,
    enabled: bool,
    actor_id: str,
    max_value: Decimal | None = None,
    allowed_risks: list[str] | None = None,
    notes: str | None = None,
) -> dict:
    if action not in DEFAULT_POLICIES:
        raise ValueError("Action is not on the server-side autonomy allowlist.")
    if not 0 <= level <= 4:
        raise ValueError("Autonomy level must be between 0 and 4.")
    forbidden = {"BYPASS_CREDIT_BLOCK", "CHANGE_PAYMENT_DESTINATION", "REFUND_PAYMENT"}
    if action in forbidden and (enabled or level != 0):
        raise ValueError("This action is permanently forbidden from autonomous execution.")
    risks = [str(x).upper() for x in (allowed_risks or [])]
    if any(r not in {"LOW", "MEDIUM", "HIGH"} for r in risks):
        raise ValueError("allowed_risks may contain LOW, MEDIUM or HIGH only.")
    row = await session.get(AutonomyPolicy, action)
    if row is None:
        row = AutonomyPolicy(action=action)
        session.add(row)
    row.level = level
    row.enabled = enabled
    row.max_value = max_value
    row.allowed_risks = risks
    row.require_verified_evidence = True
    row.notes = notes
    row.updated_by = actor_id
    await session.commit()
    await session.refresh(row)
    return {
        "action": row.action, "level": row.level, "enabled": row.enabled,
        "policy_version": row.policy_version,
        "max_value": str(row.max_value) if row.max_value is not None else None,
        "allowed_risks": row.allowed_risks,
        "require_verified_evidence": row.require_verified_evidence,
        "notes": row.notes, "updated_by": row.updated_by,
        "updated_at": row.updated_at.isoformat() if row.updated_at else None,
    }

async def evaluate_autonomy(
    session: AsyncSession,
    *,
    action: str,
    risk: str,
    value: Decimal,
    human_requested: bool,
    evidence_verified: bool,
) -> dict:
    """Return a server-side execution decision for one named action.

    L0 = observe only, L1 = human-requested action, L2+ = policy-bounded
    automatic action. A disabled policy never authorizes autonomous execution,
    but a protected human request may still perform an L1 operation through its
    dedicated RBAC endpoint.
    """
    if action not in DEFAULT_POLICIES:
        return {"allowed": False, "reason": "ACTION_NOT_ALLOWLISTED", "level": 0}
    await seed_default_autonomy_policies(session, actor_id="SYSTEM_POLICY_SEED")
    row = await session.get(AutonomyPolicy, action)
    if row is None:
        return {"allowed": False, "reason": "POLICY_MISSING", "level": 0}

    risk = str(risk or "HIGH").upper()
    if row.require_verified_evidence and not evidence_verified:
        return {"allowed": False, "reason": "VERIFIED_EVIDENCE_REQUIRED", "level": row.level}
    if human_requested:
        # Human request is still subject to all normal RBAC/domain checks in the
        # calling endpoint; this only expresses autonomy level semantics.
        return {"allowed": row.level >= 1, "reason": "HUMAN_REQUEST_L1" if row.level >= 1 else "L0_OBSERVE_ONLY", "level": row.level}
    if not row.enabled:
        return {"allowed": False, "reason": "AUTONOMY_DISABLED", "level": row.level}
    if row.level < 2:
        return {"allowed": False, "reason": "HUMAN_APPROVAL_REQUIRED", "level": row.level}
    if risk not in set(row.allowed_risks or []):
        return {"allowed": False, "reason": "RISK_OUTSIDE_POLICY", "level": row.level}
    if row.max_value is not None and Decimal(value) > Decimal(row.max_value):
        return {"allowed": False, "reason": "VALUE_OUTSIDE_POLICY", "level": row.level}
    return {"allowed": True, "reason": "POLICY_BOUNDED_AUTONOMY", "level": row.level}
